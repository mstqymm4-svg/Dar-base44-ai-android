export function filterTemplates(templates: PromptTemplate[], query: string, category: string): PromptTemplate[] {
  return templates.filter(t => {
    const matchesQuery = query === '' || 
      t.title.toLowerCase().includes(query.toLowerCase()) || 
      t.prompt.toLowerCase().includes(query.toLowerCase()) ||
      t.description.toLowerCase().includes(query.toLowerCase());
    
    const matchesCategory = category === 'All' || t.category === category;
    return matchesQuery && matchesCategory;
  });
}

export function formatCodeSnippet(code: string, language: string): string {
  return `// Language: ${language}\n// Generated by Dar Base44 AI Android\n\n${code.trim()}`;
}
